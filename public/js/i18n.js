class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('ddev_lang') || 'ta'; // Default to Tamil
  }

  get lang() {
    return this.currentLang;
  }

  set lang(l) {
    if (l === 'ta' || l === 'en') {
      this.currentLang = l;
      localStorage.setItem('ddev_lang', l);
      this.applyTranslations();
    }
  }

  t(path) {
    const keys = path.split('.');
    let curr = I18N_DATA[this.currentLang] || I18N_DATA['en'];
    for (const k of keys) {
      if (!curr || typeof curr !== 'object') return path;
      curr = curr[k];
    }
    return curr || path;
  }

  applyTranslations() {
    // Translate all elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val && typeof val === 'string') {
        el.textContent = val;
      }
    });

    // Translate placeholders with data-i18n-ph
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      const key = el.getAttribute('data-i18n-ph');
      const val = this.t(key);
      if (val && typeof val === 'string') {
        el.setAttribute('placeholder', val);
      }
    });

    // Update language toggle button text
    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
      langBtn.textContent = this.currentLang === 'ta' ? 'English (EN)' : 'தமிழ் (TA)';
      langBtn.setAttribute('title', this.currentLang === 'ta' ? 'Switch to English' : 'தமிழுக்கு மாறவும்');
    }

    // Update html lang attribute
    document.documentElement.lang = this.currentLang;
  }
}

export const i18n = new I18nManager();
